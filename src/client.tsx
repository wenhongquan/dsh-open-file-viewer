/** One file reference decoded from a `dsh-resource://` address. */
interface FileRef {
  sessionId: string
  path: string
}

/**
 * Decode a `dsh-resource://file/…` address into a session id and a path.
 * Only `session`-scoped addresses are handled: an `absolute` address names a
 * file outside any session workspace, which the Remote read cannot scope.
 */
function parseFileAddress(address: string): FileRef | null {
  if (!address.startsWith(FILE_ADDRESS_PREFIX)) return null
  const query = address.search(/[?#]/)
  const body = address.slice(FILE_ADDRESS_PREFIX.length, query === -1 ? undefined : query)
  const [scope, ...rest] = body.split('/')
  if (scope !== 'session') return null
  const [rawId, ...segments] = rest
  if (rawId === undefined || rawId === '' || segments.length === 0) return null
  try {
    return {
      sessionId: decodeURIComponent(rawId),
      path: segments.map(decodeURIComponent).join('/'),
    }
  } catch {
    // A malformed percent-escape is not a file we can open.
    return null
  }
}

function baseName(path: string): string {
  const parts = path.split(/[\\/]/)
  return parts[parts.length - 1] ?? path
}

/** Whether a file's suffix is one this preview claims. */
function isClaimed(name: string): boolean {
  const dot = name.lastIndexOf('.')
  if (dot <= 0) return false
  return EXTENSION_SET.has(name.slice(dot + 1).toLowerCase())
}

interface RemoteBytes {
  readonly data: Uint8Array
  readonly eof: boolean
}

/**
 * The Typert Remote call envelope: every generated namespace method answers
 * `RemoteResult<T>`, never the business value directly — an unreachable or
 * refused read arrives as `{ ok: false, error }`.
 */
type RemoteEnvelope<T> = { readonly ok: true; readonly value: T } | {
  readonly ok: false
  readonly error: { readonly code?: string; readonly message?: string }
}

/**
 * The platform's workspace-file Remote. Only the one method used here is
 * modelled; the service carries more (stat, list, text reads).
 */
interface WorkspaceFilesRemote {
  readBytes: (
    scope: unknown,
    path: string,
    options: { range?: { offset?: number; length?: number } },
    signal: AbortSignal,
  ) => Promise<RemoteEnvelope<RemoteBytes>>
}

/**
 * Read a whole file through the Remote.
 *
 * A complete-file read (`{ range: undefined }`) is REFUSED above the
 * deployment's `maxFileBytes` (32 MiB by default) rather than truncated, and
 * one window may not exceed `maxBytes` (2 MiB), so the file is paged: the
 * first window also reports the total size, which bounds the loop and lets an
 * oversized file fail with a real message instead of a mysterious error.
 */
const WINDOW_BYTES = 2 * 1024 * 1024

/** One unwrapped byte window: envelope failures become readable errors. */
async function readWindow(
  remote: WorkspaceFilesRemote,
  ref: FileRef,
  options: { range?: { offset?: number; length?: number } },
  signal: AbortSignal,
): Promise<RemoteBytes> {
  const result = await remote.readBytes(ref.sessionId, ref.path, options, signal)
  if (!result.ok) {
    throw new Error(
      `文件读取失败（${result.error?.code ?? 'unknown'}${result.error?.message ? `: ${result.error.message}` : ''}）`,
    )
  }
  return result.value
}

async function readWholeFile(
  remote: WorkspaceFilesRemote,
  ref: FileRef,
  signal: AbortSignal,
): Promise<Uint8Array> {
  const first = await readWindow(remote, ref, {}, signal)
  if (first.eof) return first.data

  const chunks: Uint8Array[] = [first.data]
  let offset = first.data.length
  while (true) {
    const next = await readWindow(
      remote,
      ref,
      { range: { offset, length: WINDOW_BYTES } },
      signal,
    )
    if (next.data.length === 0) break
    chunks.push(next.data)
    offset += next.data.length
    if (next.eof) break
  }

  const total = chunks.reduce((sum, chunk) => sum + chunk.length, 0)
  const merged = new Uint8Array(total)
  let at = 0
  for (const chunk of chunks) {
    merged.set(chunk, at)
    at += chunk.length
  }
  return merged
}

interface ViewerHandle {
  destroy?: () => void
  resize?: () => void
}

/**
 * The dsh-better-sidebar file-viewer service face this plugin integrates
 * with (structural slice; the real contract lives in dsh-better-sidebar).
 * `registerFileViewer` contributes a previewer to the editor's own registry:
 * files opened from its file tree then render here instead of its binary
 * download fallback. Optional by design — when the plugin is absent the
 * registration is skipped and the native claim path serves everything.
 */
interface BetterSidebarService {
  registerFileViewer?: (descriptor: {
    id: string
    title?: string
    exts: readonly string[]
    priority?: number
    fetchStrategy: 'custom'
    load?: (path: string, scope: { sessionId: string }, signal?: AbortSignal) => Promise<unknown>
    component: (props: { path: string; customData?: unknown }) => unknown
  }) => () => void
}

/** Props better-sidebar hands a file viewer component (structural slice). */
interface BetterSidebarViewerProps {
  readonly path: string
  readonly customData?: unknown
}

/**
 * better-sidebar seat: mount the core viewer over the bytes the descriptor's
 * `load` fetched. The editor's own chrome stays; this draws the document
 * body only, exactly like the native pane body does.
 */
function BetterSidebarViewer({ path, customData }: BetterSidebarViewerProps) {
  const hostRef = useRef<HTMLDivElement | null>(null)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    const host = hostRef.current
    if (host === null) return
    const bytes = customData
    if (!(bytes instanceof Uint8Array) || bytes.byteLength === 0) {
      setError('文件内容读取失败')
      return
    }
    installStyle()
    host.replaceChildren()
    setError(null)
    // An OWNED ArrayBuffer (see the native pane body for why not `bytes.buffer`).
    const buffer = new ArrayBuffer(bytes.byteLength)
    new Uint8Array(buffer).set(bytes)
    const viewer = createViewer({
      container: host,
      file: buffer,
      fileName: baseName(path),
      width: '100%',
      height: '100%',
      fit: 'contain',
      toolbar: true,
      theme: 'auto',
      plugins: previewPlugins(),
    }) as ViewerHandle
    requestAnimationFrame(() => { viewer?.resize?.() })
    return () => {
      try { viewer?.destroy?.() } catch { /* already torn down */ }
      host.replaceChildren()
    }
  }, [path, customData])

  if (error !== null) {
    return createElement('div', { style: { padding: '16px', color: '#c0392b' } }, error)
  }
  return createElement('div', {
    ref: hostRef,
    style: { width: '100%', height: '100%', overflow: 'hidden' },
  })
}

/** Props the tab seat injects into a pane body. */
interface PaneBodyProps {
  readonly useTabInfo: () => { readonly tab: { readonly contentId: string } }
}

/**
 * The pane body. It owns reading the file and rendering it; the tab seat has
 * already decided that this address belongs to us.
 */
function createBodyComponent(remote: WorkspaceFilesRemote | undefined) {
  return function OpenFileViewerBody({ useTabInfo }: PaneBodyProps) {
    const hostRef = useRef<HTMLDivElement | null>(null)
    const [error, setError] = useState<string | null>(null)
    const { tab } = useTabInfo()
    const address = tab.contentId

    useEffect(() => {
      installStyle()
      const host = hostRef.current
      if (host === null) return

      const ref = parseFileAddress(address)
      if (ref === null) {
        setError('无法识别的文件地址')
        return
      }
      if (remote === undefined) {
        setError('宿主未提供文件读取服务')
        return
      }

      const controller = new AbortController()
      let disposed = false
      let viewer: ViewerHandle | null = null
      host.replaceChildren()
      setError(null)

      void (async () => {
        try {
          const bytes = await readWholeFile(remote, ref, controller.signal)
          if (disposed) return
          const fileName = baseName(ref.path)
          // An OWNED ArrayBuffer, not `bytes.buffer`: that would alias the
          // reader's storage, and `Uint8Array.buffer` types as
          // `ArrayBufferLike` (possibly shared), which the viewer's source
          // type does not accept.
          //
          // Passed raw rather than wrapped in a Blob: `normalizeFile` resolves
          // the MIME type as `mimeType || source.type || extensionMimeMap[…]`,
          // so a Blob's own type short-circuits the extension lookup and pins
          // every file to one value — images stop rendering and pdfjs stops
          // being recognised.
          const buffer = new ArrayBuffer(bytes.byteLength)
          new Uint8Array(buffer).set(bytes)
          viewer = createViewer({
            container: host,
            file: buffer,
            fileName,
            width: '100%',
            height: '100%',
            fit: 'contain',
            toolbar: true,
            theme: 'auto',
            plugins: previewPlugins(),
            onError: (err: unknown) => {
              if (!disposed) setError(err instanceof Error ? err.message : String(err))
            },
          })
          // The pane is measured after this effect in some mount orders, so
          // one deferred pass settles the initial fit.
          requestAnimationFrame(() => {
            if (!disposed) viewer?.resize?.()
          })
        } catch (err) {
          if (disposed || controller.signal.aborted) return
          setError(err instanceof Error ? err.message : String(err))
        }
      })()

      return () => {
        disposed = true
        controller.abort()
        viewer?.destroy?.()
      }
    }, [address])

    if (error !== null) {
      return createElement(
        'div',
        { className: STATUS_CLASS, 'data-kind': 'error', role: 'alert' },
        error,
      )
    }
    return createElement('div', { className: PANE_CLASS, ref: hostRef })
  }
}

/**
 * Platform services this plugin waits for.
 *
 * Required, not decorative: the loader reads `inject` to decide when to run
 * `apply`. Without it `apply` runs before the services exist, every `ctx.get`
 * answers `undefined`, and the registration silently never happens.
 *
 * `remote.workspaceFiles` is the namespace-level service the gateway provides
 * only after the api-remotes assembly mounts it — waiting on the bare `remote`
 * service races the mount and captures `workspaceFiles` as undefined.
 */
const inject = ['slots', 'sidebarRightTabs', 'remote', 'remote.workspaceFiles']

interface Slots {
  inject: (name: string, factory: () => void) => void
  register: (descriptor: unknown, component: unknown) => () => void
}

interface TabRegistry {
  register: (definition: unknown) => () => void
}

interface ClientContext {
  effect: (fn: () => (() => void) | void, label?: string) => void
  get: (name: string) => unknown
}

/** Client plugin body. */
function apply(ctx: ClientContext): void {
  installStyle()

  ctx.effect(() => {
    const slots = ctx.get('slots') as Slots | undefined
    const tabs = ctx.get('sidebarRightTabs') as TabRegistry | undefined
    const remote = ctx.get('remote') as { workspaceFiles?: WorkspaceFilesRemote } | undefined
    if (slots === undefined || tabs === undefined) {
      console.warn('[dsh-open-file-viewer] platform services are not available')
      return
    }

    const component = createBodyComponent(remote?.workspaceFiles)
    const disposers: (() => void)[] = []

    // Stage one: claim workspace file addresses at the highest band. The kind
    // is this plugin's own, so the shipped `text` type keeps its registration
    // and only loses the RANKING for these addresses.
    disposers.push(
      tabs.register({
        id: PREVIEW_ID,
        kind: PREVIEW_KIND,
        patterns: ['dsh-resource://file/**'],
        priority: 'extension',
        canOpen: (address: string) => {
          const ref = parseFileAddress(address)
          return ref !== null && isClaimed(baseName(ref.path))
        },
        title: (address: string) => {
          const ref = parseFileAddress(address)
          return ref === null ? address : baseName(ref.path)
        },
      }),
    )

    // Stage two: the body, under the type id the seat dispatches.
    slots.inject('sidebar.right.pane.tab', () => {
      disposers.push(
        slots.register({ name: 'sidebar.right.pane.tab', key: PREVIEW_ID }, component),
      )
    })

    // Stage three: dsh-better-sidebar's editor claims file opens from its own
    // file tree with an extension-band registration of its own, then renders
    // from its PRIVATE viewer registry — without a registration there, every
    // format outside its HOST_OWNED_EXTS (3D, CAD, GIS, media, archives)
    // lands on its "cannot be previewed" download face. Contribute this
    // previewer through its public `registerFileViewer` so those opens render
    // here. The service is optional: when the plugin is absent the short
    // poll below gives up and the native claim path keeps serving every
    // surface that routes through it.
    const filesRemote = remote?.workspaceFiles
    let clearBetterSidebarPoll: (() => void) | undefined
    if (filesRemote !== undefined) {
      let pollTimer: ReturnType<typeof setTimeout> | undefined
      let pollsLeft = 30
      const registerIntoBetterSidebar = (): void => {
        pollTimer = undefined
        const betterSidebar = ctx.get('betterSidebar') as BetterSidebarService | undefined
        const register = betterSidebar?.registerFileViewer
        if (register === undefined) {
          // Retry while the service is missing — better-sidebar may activate
          // after this plugin. Without a timer in this realm (the standalone
          // verify sandbox) retrying is impossible; give up and leave the
          // native claim path to serve every open.
          if (pollsLeft > 0 && typeof setTimeout === 'function') {
            pollsLeft -= 1
            pollTimer = setTimeout(registerIntoBetterSidebar, 500)
          }
          return
        }
        disposers.push(register({
          id: PREVIEW_ID,
          title: 'Open File Viewer',
          exts: betterSidebarExts(),
          priority: 10,
          fetchStrategy: 'custom',
          load: (path: string, scope: { sessionId: string }, signal?: AbortSignal) =>
            readWholeFile(filesRemote, { sessionId: scope.sessionId, path }, signal ?? new AbortController().signal),
          component: BetterSidebarViewer,
        }))
        console.info('[dsh-open-file-viewer] registered the previewer with dsh-better-sidebar')
      }
      registerIntoBetterSidebar()
      clearBetterSidebarPoll = () => { if (pollTimer !== undefined) clearTimeout(pollTimer) }
    }

    console.info('[dsh-open-file-viewer] claimed the document preview kind', PREVIEW_ID)

    return () => {
      clearBetterSidebarPoll?.()
      for (const dispose of disposers.reverse()) {
        try {
          dispose()
        } catch {
          /* a seat already torn down is not an error */
        }
      }
    }
  }, 'dsh-open-file-viewer: document preview registration')
}

