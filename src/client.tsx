/**
 * Open File Viewer preview for DSH.
 *
 * STANDALONE: this plugin depends only on DSH's own platform services
 * (`slots`, `sidebarRightTabs`, `remote`) and on `@open-file-viewer/core`.
 * It does not use, or require, any other preview plugin.
 *
 * It hooks the same seam DSH's own preview uses:
 *
 *   1. `sidebarRightTabs.register(definition)` declares a tab TYPE for the
 *      existing document kind. A kind with no type in force renders the
 *      platform's "nothing can view this" notice, so registering one is what
 *      makes file clicks open a preview at all.
 *   2. `slots.register({ name: 'sidebar.right.pane.tab', key: id }, Body)`
 *      supplies the body under that type's own `id`.
 *
 * File bytes are read straight from the platform's workspace Remote
 * (`readBytes`), paged because a complete-file read is refused above the
 * deployment cap (32 MiB by default) rather than truncated.
 */
